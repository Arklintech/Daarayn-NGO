/**
 * lib/intake/schema.ts  (D37, ISOLATED: nothing in the active donation path imports this module)
 *
 * The durable intake record. One row per accepted submission in the `Donation_Intake` worksheet. The row is written once by the intake step
 * (literal-safe, atomic) and afterwards changed ONLY by the finaliser, and only in the cells it owns (state, retry count, error category,
 * donation id, timestamps, payload scrub). The donor-facing submission reference is a pure function of the idempotency key and the payload hash.
 */
import crypto from "crypto";
import { registerSchema } from "../google/schemaRegistry";

export const INTAKE_SHEET = "Donation_Intake";
export const INTAKE_HEADERS = [
  "submissionRef",
  "idempotencyKey",
  "payloadHash",
  "payload",
  "receivedAt",
  "state",
  "retryCount",
  "lastErrorCategory",
  "donationId",
  "completedAt",
  "updatedAt",
];

// Registered so a cold instance fetches this worksheet's header row in the SAME request as the other known tabs (live: it was a separate read per instance).
registerSchema(INTAKE_SHEET, INTAKE_HEADERS);

/** Schema contract version of the intake worksheet. A change of INTAKE_HEADERS requires a new version and a deliberate migration. */
export const INTAKE_SCHEMA_VERSION = 1;

export class IntakeSchemaError extends Error {
    constructor(detail: string) {
        super(`The ${INTAKE_SHEET} worksheet does not match schema version ${INTAKE_SCHEMA_VERSION}: ${detail}. Nothing was written.`);
        this.name = "IntakeSchemaError";
    }
}

/** The contract columns must be exactly INTAKE_HEADERS from column A; columns to the right are allowed. Anything else fails closed. */
export function assertIntakeSchema(actual: string[]): void {
    for (let i = 0; i < INTAKE_HEADERS.length; i++) {
        if (actual[i] !== INTAKE_HEADERS[i]) throw new IntakeSchemaError(`column ${i + 1} is "${actual[i] ?? ""}", expected "${INTAKE_HEADERS[i]}"`);
    }
}

export type IntakeState = "RECEIVED" | "ID_ASSIGNED" | "COMPLETE" | "REJECTED" | "RETRY_PENDING" | "FAILED_REQUIRES_REVIEW" | "DUPLICATE";
/** States the finaliser still works on. */
export const WORKING_STATES: ReadonlySet<string> = new Set(["RECEIVED", "ID_ASSIGNED", "RETRY_PENDING"]);
/** Never changes again without a human decision (DUPLICATE is internal: the donor sees the canonical row's state for the same reference). */
export const TERMINAL_STATES: ReadonlySet<string> = new Set(["COMPLETE", "REJECTED", "FAILED_REQUIRES_REVIEW", "DUPLICATE"]);

/** The minimised payload: only what is needed to build the donation. It is scrubbed (emptied) when the donation is COMPLETE; the hash stays. */
export interface IntakePayload {
  donorName: string;
  donorContact: string;
  amount: number;
  currency: string;
  upiRef: string;
  /** Display title of the cause choice (computed at intake from the fresh catalogue). */
  causeTitle: string;
  /** Set only when exactly one cause was chosen. */
  causeId: string;
  selection: { causeId: string; causeName: string }[];
  proofDriveFileId: string;
}

/** JSON with sorted keys, so the same payload always hashes the same. */
export function canonicalJson(v: unknown): string {
  if (v === null || typeof v !== "object") return JSON.stringify(v);
  if (Array.isArray(v)) return `[${v.map(canonicalJson).join(",")}]`;
  const o = v as Record<string, unknown>;
  return `{${Object.keys(o).sort().map((k) => `${JSON.stringify(k)}:${canonicalJson(o[k])}`).join(",")}}`;
}

/**
 * Hash of the DONOR-SUPPLIED content. The proof file id is excluded on purpose: it is generated by the server on every attempt (a replay uploads a
 * new copy), so including it would give every replay another hash, another reference and a "key reused with another payload" rejection.
 */
export const payloadHash = (p: IntakePayload): string => {
  const { proofDriveFileId: _proof, ...donorContent } = p;
  void _proof;
  return crypto.createHash("sha256").update(canonicalJson(donorContent)).digest("hex");
};

const B32 = "0123456789ABCDEFGHJKMNPQRSTVWXYZ";
/** SUB-XXXXXXXXXXXX (60 bits): the same key and payload always give the same reference, so a replay needs no read; another payload under the same key gets another reference. */
export function submissionReference(idempotencyKey: string, hash: string): string {
  const digest = crypto.createHash("sha256").update(`${idempotencyKey}:${hash}`).digest();
  let out = "";
  let acc = 0;
  let bits = 0;
  for (let i = 0; out.length < 12; ) {
    acc = (acc << 8) | digest[i++];
    bits += 8;
    while (bits >= 5 && out.length < 12) {
      out += B32[(acc >>> (bits - 5)) & 31];
      bits -= 5;
      acc &= (1 << bits) - 1;
    }
  }
  return `SUB-${out}`;
}

export interface IntakeEntry {
  rowNumber: number;
  submissionRef: string;
  idempotencyKey: string;
  payloadHash: string;
  payload: IntakePayload | null;
  receivedAt: string;
  state: string;
  retryCount: number;
  lastErrorCategory: string;
  donationId: string;
  completedAt: string;
  /** False when the row cannot be trusted: the reference or the hash does not match its content, or a non-final row has no readable payload. */
  valid: boolean;
}

export function parseIntakeRow(rowNumber: number, r: Record<string, any>): IntakeEntry {
  const submissionRef = String(r.submissionRef || "");
  const idempotencyKey = String(r.idempotencyKey || "");
  const hash = String(r.payloadHash || "");
  const state = String(r.state || "");
  let payload: IntakePayload | null = null;
  const raw = String(r.payload || "");
  if (raw) {
    try {
      payload = JSON.parse(raw);
    } catch {
      payload = null;
    }
  }
  // A scrubbed payload (emptied when the donation completed) is valid as long as the row still names its donation: a later bookkeeping write may change the state cell only.
  const scrubbed = !raw && Boolean(String(r.donationId || ""));
  let valid = Boolean(submissionRef && idempotencyKey && hash && submissionRef === submissionReference(idempotencyKey, hash));
  if (valid && !scrubbed) {
    valid = Boolean(payload && typeof payload.donorName === "string" && Number(payload.amount) > 0 && payloadHash(payload) === hash);
  }
  return {
    rowNumber,
    submissionRef,
    idempotencyKey,
    payloadHash: hash,
    payload,
    receivedAt: String(r.receivedAt || ""),
    state,
    retryCount: Number(r.retryCount) || 0,
    lastErrorCategory: String(r.lastErrorCategory || ""),
    donationId: String(r.donationId || ""),
    completedAt: String(r.completedAt || ""),
    valid,
  };
}
